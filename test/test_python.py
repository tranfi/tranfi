def test_jsonl_malformed_records():
    step = tf.codec.jsonl_decode(on_error='warn', max_error_bytes=12)
    assert step['args']['on_error'] == 'warn'
    assert step['args']['max_error_bytes'] == 12

    p = tf.pipeline([
        tf.codec.jsonl(on_error='warn'),
        tf.codec.csv_encode(),
    ])
    data = (
        b'{"name":"Alice","age":30}\n'
        b'not json\n'
        b'[1,2]\n'
        b'{"name":"Bob","age":25}\n'
    )
    result = p.run(input=data, chunk_size=9)
    assert 'Alice' in result.output_text
    assert 'Bob' in result.output_text
    assert 'not json' not in result.output_text
    errors = result.errors.decode('utf-8')
    assert 'jsonl_malformed' in errors
    assert '"action":"warn"' in errors
    assert '"severity":"warning"' in errors
    assert '"line":2' in errors
    assert '"line":3' in errors
    assert 'JSONL record is not an object' in errors

    skipped = tf.pipeline([tf.codec.jsonl(), tf.codec.csv_encode()]).run(input=data)
    assert 'Alice' in skipped.output_text
    assert 'Bob' in skipped.output_text
    assert skipped.errors == b''

    quarantined = tf.pipeline([
        tf.codec.jsonl(on_error='quarantine', max_error_bytes=8),
        tf.codec.csv_encode(),
    ]).run(input=b'{"name":"Alice","age":30}\nnot-json-record-long\n')
    q_errors = quarantined.errors.decode('utf-8')
    assert '"action":"quarantine"' in q_errors
    assert '"severity":"error"' in q_errors
    assert '"raw_bytes":20' in q_errors
    assert '"raw":"not-json"' in q_errors
    assert '"truncated":true' in q_errors
    assert 'record-long' not in q_errors

    failing = tf.pipeline([
        tf.codec.jsonl(on_error='fail'),
        tf.codec.csv_encode(),
    ])
    with pytest.raises(RuntimeError, match='jsonl decode failed at line 2'):
        failing.run(input=b'{"name":"Alice","age":30}\nnot json\n')


