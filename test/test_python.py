def test_ops_tail():
    data = bytes([10]).join([
        b'name,age', b'Alice,30', b'Bob,25', b'Charlie,35', b''
    ])
    p = tf.pipeline([
        tf.codec.csv(),
        tf.ops.tail(2),
        tf.codec.csv_encode(),
    ])
    result = p.run(input=data)
    text = result.output_text
    assert 'Bob' in text
    assert 'Charlie' in text
    assert 'Alice' not in text

    head_alias = tf.pipeline([
        tf.codec.csv(),
        tf.ops.slice_head(2),
        tf.codec.csv_encode(),
    ])
    head_result = head_alias.run(input=data)
    assert head_result.output_text.strip().splitlines() == [
        'name,age', 'Alice,30', 'Bob,25'
    ]

    tail_alias = tf.pipeline([
        tf.codec.csv(),
        tf.ops.slice_tail(2),
        tf.codec.csv_encode(),
    ])
    tail_result = tail_alias.run(input=data)
    assert tail_result.output_text.strip().splitlines() == [
        'name,age', 'Bob,25', 'Charlie,35'
    ]


