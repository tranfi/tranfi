def test_json_schema_filter_and_annotate():
    schema = {
        'type': 'object',
        'required': ['user'],
        'properties': {
            'user': {
                'type': 'object',
                'required': ['name', 'age'],
                'properties': {
                    'name': {'type': 'string', 'minLength': 1},
                    'age': {'type': 'integer', 'minimum': 18},
                },
            },
        },
    }
    p = tf.pipeline([
        tf.codec.text(batch_size=1),
        tf.ops.json_schema(schema, mode='filter', audit=True, audit_limit=1),
        tf.codec.csv_encode(),
    ])
    data = (
        b'{"user":{"name":"Ada","age":42}}\n'
        b'{"user":{"name":"Ben","age":7}}\n'
        b'{"user":{"name":"Cara"}}\n'
        b'not json\n'
    )
    filtered = p.run(input=data)
    text = filtered.output_text
    assert 'Ada' in text
    assert 'Ben' not in text
    assert 'Cara' not in text
    assert 'not json' not in text
    assert '"type":"audit"' in filtered.stats_text
    assert '"op":"json-schema"' in filtered.stats_text
    assert '"reason":"json_schema_failed"' in filtered.stats_text
    assert '"row":2' in filtered.stats_text
    assert 'schema_mismatch' in filtered.stats_text
    assert 'Ben' in filtered.stats_text
    assert 'Cara' not in filtered.stats_text

    nested_schema = {
        'type': 'object',
        'required': ['city', 'zip'],
        'properties': {
            'city': {'type': 'string', 'enum': ['NY', 'LA']},
            'zip': {'type': 'integer', 'minimum': 10000},
        },
    }
