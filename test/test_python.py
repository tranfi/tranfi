def test_csv_comments_empty_rows_and_trim_control():
    step = tf.codec.csv(comment='#', skip_empty_rows=True, trim_ws=False, skip=2, n_max=3)
    assert step['args']['comment'] == '#'
    assert step['args']['skip_empty_rows'] is True
    assert step['args']['trim_ws'] is False
    assert step['args']['skip'] == 2
    assert step['args']['n_max'] == 3

    p = tf.pipeline([
        tf.codec.csv(batch_size=1, comment='#', skip_empty_rows=True),
        tf.codec.csv_encode(),
    ])
    data = b'# generated\nname,score,note\n Alice , 10 , ok # trailing\n\n"Bob # literal",20," keep # inside "\n'
    result = p.run(input=data, chunk_size=7)
    text = result.output_text
    assert 'Alice,10,ok' in text
    assert 'Bob # literal,20, keep # inside ' in text
    assert 'generated' not in text
    assert 'trailing' not in text

    no_trim = tf.pipeline([
        tf.codec.csv(trim_ws=False),
        tf.codec.csv_encode(),
    ]).run(input=b'name,score\n Alice , 10 \n')
    assert ' Alice , 10 ' in no_trim.output_text

    skipped = tf.pipeline([
        tf.codec.csv(skip=2, comment='#'),
        tf.codec.csv_encode(),
    ]).run(input=b'generated by system\nexported today\n# ignored after skip\nname,score\nAlice,10\nBob,20\n', chunk_size=11)
    assert 'name,score' in skipped.output_text
    assert 'Alice,10' in skipped.output_text
    assert 'Bob,20' in skipped.output_text
    assert 'generated by system' not in skipped.output_text
    assert 'exported today' not in skipped.output_text
    assert 'ignored after skip' not in skipped.output_text

    limited = tf.pipeline([
        tf.codec.csv(n_max=2, batch_size=1),
        tf.codec.csv_encode(),
    ]).run(input=b'name,score\nAlice,10\nBob,20\nCara,30\n', chunk_size=9)
    assert 'Alice,10' in limited.output_text
    assert 'Bob,20' in limited.output_text
    assert 'Cara,30' not in limited.output_text

    header_only = tf.pipeline([
        tf.codec.csv(max_rows=0),
        tf.codec.csv_encode(),
    ]).run(input=b'name,score\nAlice,10\n')
    assert header_only.output_text == 'name,score\n'


