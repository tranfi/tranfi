def test_native_memory_policy():
    p = tf.pipeline([tf.codec.csv(), tf.ops.sort(['age']), tf.codec.csv_encode()])
    with pytest.raises(RuntimeError, match="blocking step 'sort'"):
        p.run(input=b'name,age\nAlice,30\nBob,25\n')
    result = p.run(input=b'name,age\nAlice,30\nBob,25\n', allow_blocking=True)
    assert 'Bob,25' in result.output_text

    capped = tf.pipeline([tf.codec.csv(), tf.ops.unique(['name'], max_keys=2), tf.codec.csv_encode()])
    result = capped.run(input=b'name,age\nAlice,30\nBob,25\n', memory='64KB')
    assert 'Alice,30' in result.output_text
    with pytest.raises(RuntimeError, match='estimated native key-state memory'):
        capped.run(input=b'name,age\nAlice,30\nBob,25\n', memory='1KB')

    byte_capped = tf.pipeline([tf.codec.csv(), tf.ops.unique(['name'], max_state_bytes=4096), tf.codec.csv_encode()])
    result = byte_capped.run(input=b'name,age\nAlice,30\nBob,25\n', memory='64KB')
    assert 'Alice,30' in result.output_text
    with pytest.raises(RuntimeError, match='max_state_bytes=2048'):
        tf.pipeline([tf.codec.csv(), tf.ops.unique(['name'], max_state_bytes=2048), tf.codec.csv_encode()]).run(input=b'name,age\nAlice,30\n')

